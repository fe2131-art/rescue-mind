def study_counts_from_rows(rows):
    """rows: the data rows of tab_prereg.tex (LaTeX source lines)."""
    body = [x for x in rows if not x.startswith('C (v3.3)')]
    return {
        'n': len(body),
        'ok': sum('checkmark' in x for x in body),
        'same': sum('same commit' in x for x in body),
        'pending': sum('pending' in x.split('&')[2] or 'pending' in x.split('&')[-1] or 'not run' in x.split('&')[2] for x in body),
    }


def study_counts():
    """{'n','ok','same','pending','with_results'} from the generated Table S9, or None when it does not exist yet."""
    f = RES.parents[1] / 'docs/paper/tab_prereg.tex'
    if snapshot_mode() and (snapshot_dir() / 'paper/tab_prereg.tex').is_file():      # the snapshot build has its own table (same rows, "not run" cells)
        f = snapshot_dir() / 'paper/tab_prereg.tex'
    if not f.is_file():
        return None
    rows = [x for x in f.read_text(encoding='utf8').splitlines() if x.count('&') >= 4 and not x.startswith('Study')]
    c = study_counts_from_rows(rows)
    c['with_results'] = c['n'] - c['pending']
    return c


