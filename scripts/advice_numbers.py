def pending_studies():
    return {k: (RES / f).is_file() for k, f in (('IF', 'if_summary.json'), ('B', 'b_summary.json'))}


def study_counts_from_rows(rows):
    """rows: the data rows of tab_prereg.tex (LaTeX source lines)."""
    body = [x for x in rows if not x.startswith('C (v3.3)')]
    return {
        'n': len(body),
        'ok': sum('checkmark' in x for x in body),
        'same': sum('same commit' in x for x in body),
        'pending': sum('pending' in x.split('&')[2] or 'pending' in x.split('&')[-1] for x in body),
    }


def study_counts():
    """{'n','ok','same','pending','with_results'} from the generated Table S9, or None when it does not exist yet."""
    f = RES.parents[1] / 'docs/paper/tab_prereg.tex'
    if not f.is_file():
        return None
    rows = [x for x in f.read_text(encoding='utf8').splitlines() if x.count('&') >= 4 and not x.startswith('Study')]
    c = study_counts_from_rows(rows)
    c['with_results'] = c['n'] - c['pending']
    return c


def study_phrase():
    """'研究 23 本（うち登録が結果より前と監査で確認できたもの 14、結果待ち 9）' - the one sentence form of the count."""
    c = study_counts()
    if not c:
        return '研究（事前登録つき）'
    return f"研究 {c['n']} 本（うち事前登録の時系列監査で、登録が結果より前と確認できたもの {c['ok']}、結果待ち {c['pending']}）"


def study_phrase_en():
    c = study_counts()
    if not c:
        return 'The studies are pre-registered'
    return (f"We ran {c['n']} studies, each with a frozen registration (`experiments/PREREGISTRATION_*.md`); for {c['ok']} of them the audit verifies that the registration "
            f"commit precedes the first results, {c['pending']} have no results yet and register when the integration branch is merged")
