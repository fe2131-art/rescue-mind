_NUMWORD = {0: 'zero', 1: 'one', 2: 'two', 3: 'three', 4: 'four', 5: 'five', 6: 'six', 7: 'seven', 8: 'eight', 9: 'nine', 10: 'ten', 11: 'eleven', 12: 'twelve'}


def failed_claims():
    """List of {'key', 'tex', 'en', 'ja'} for every registered claim that did not hold, in the order they were run."""
    out = [dict(key='T1', tex=r"T1's 2\% bound", en="T1's 2% bound", ja='T1の「誤許可2%未満」'),
           dict(key='F', tex='F', en='F', ja='F（問い方と切り出し）'),
           dict(key='T2', tex='T2', en='T2', ja='T2')]
    f = _load('f_summary.json')
    if f is not None and f['primary']['mcnemar_p'] < 0.05:
        out = [c for c in out if c['key'] != 'F']          # F held after all: drop it, the list follows the result file
    j = _load('j_summary.json')
    if j is not None and not (j['P1_runs_on_one_v100']['supported'] and j['P2_no_extra_unsafe']['supported']):
        out.append(dict(key='J', tex='J', en='J', ja='J（第2のチェッカー）'))
    v = _load('v_summary.json')
    if v is not None and not v['claim_memory_under_random_change']:
        out.append(dict(key='V4', tex='V4 (memory under random change)', en='V4 (memory under random change)', ja='V4（ランダムな変化での記憶の安全）'))
    w = _load('w_summary.json')
    if w is not None:
        wf = w_facts()
        if wf is not None and wf['n_dist'] == 0:
            out.append(dict(key='W-b', tex='W-b (hazard rule beats prior art)', en='W-b (hazard rule beats prior art)', ja='W-b（危険判定の規則が先行手法に勝つ）'))
    return out


