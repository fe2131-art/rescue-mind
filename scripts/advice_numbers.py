#!/usr/bin/env python3
"""I-23 / I-24 numbers for the README, the explanatory PDF and the consistency check (single source: the result files).

  smt_facts()     <- experiments/results/smt_advice_proof.json   (z3 proofs, differential test, injected bugs)
  credit_facts()  <- experiments/results/advice_credit_horizon.json  (descriptive 100-mission model of the advice credit; not registered)
  v_facts()       <- experiments/results/v_summary.json  (study V; one place for the wording of the model and memory claims in README, report, YouTube)
  pending_studies() -> {'IF': bool, 'B': bool}  (True = summary file exists)
  study_counts()  <- docs/paper/tab_prereg.tex (generated by paper_numbers.py from the PREREGISTRATION_* files and git history):
                     THE definition of "number of studies" used by the README, the report, the paper and check_consistency:
                     n = every row of Table S9 except C (the initial evaluation) = the studies of Supp. Table S12;
                     ok = registration commit verified to precede the first results commit; same = same commit (not verifiable);
                     pending = no results yet (their registration is committed with the integration merge).

Every function returns None when its file is missing, so a document says 'pending' instead of inventing a number.
"""
from __future__ import annotations
import json
from pathlib import Path

RES = Path(__file__).resolve().parents[1] / 'experiments/results'


def _load(name):
    f = RES / name
    try:
        return json.loads(f.read_text(encoding='utf8')) if f.is_file() else None
    except ValueError:
        return None


def smt_facts():
    d = _load('smt_advice_proof.json')
    if not d:
        return None
    proofs = d['proofs']
    diff = d['differential']
    mut = d['code_mutants']
    nec = d.get('necessity', [])
    return {
        'unsat': sum(p['result'] == 'unsat' for p in proofs),
        'queries': len(proofs),
        'cases': d['differential_total_cases'],
        'groups': len(diff), 'per_group': diff['plan']['n'],
        'disagreements': sum(v.get('disagreements', 0) for v in diff.values()),
        'mutants': len(mut),
        'caught': sum(1 for m in mut if m['detect_differential']['detected'] or m['detect_property']['detected']),
        'necessity_relaxing': sum(1 for n in nec if n['result'] == 'sat'),
        'necessity_tighten_unsat': any(n['result'] == 'unsat' and n['interface'].startswith('tighten-only') for n in nec),
        'unsafe_rate': next((n['counterexample']['unsafe_rate'] for n in nec if n['result'] == 'sat' and n.get('counterexample')), None),
        'eps_any': next((n['counterexample']['eps_any'] for n in nec if n['result'] == 'sat' and n.get('counterexample')), None),
        'z3': d['env']['z3'],
    }


def credit_facts():
    c = _load('advice_credit_horizon.json')
    if not c:
        return None
    r = c['runs']
    last = lambda k: r[k]['series'][-1]
    p = c['params']
    return {
        'liar_no': last('k4/liar/monotone')['extra_s'], 'liar_yes': last('k4/liar/credit')['extra_s'],
        'adaptive_yes': last('k4/farmer/credit')['extra_s'],
        'honest_no': -last('k4/honest/monotone')['extra_s'], 'honest_yes': -last('k4/honest/credit')['extra_s'],
        'flood_no': last('k4/flooder_real/monotone')['false_refusals'], 'flood_yes': last('k4/flooder_real/credit')['false_refusals'],
        'flood_delta': c['delta_real'],
        'noisy_keep': 100 * last('k4/noisy/credit')['extra_s'] / last('k4/noisy/monotone')['extra_s'],
        'missions': len(r['k4/liar/credit']['series']),
        'unsafe_equal': all(v.get('unsafe') == r[k.replace('/credit', '/monotone')].get('unsafe')
                            for k, v in r.items() if k.endswith('/credit')),
        'k4': {src: {'extra_s': (last(f'k4/{src}/monotone')['extra_s'], last(f'k4/{src}/credit')['extra_s']),
                     'false_refusals': (last(f'k4/{src}/monotone')['false_refusals'], last(f'k4/{src}/credit')['false_refusals'])}
               for src in ('honest', 'noisy', 'liar', 'farmer', 'flooder', 'flooder_real')},
        'c_loc': p['c_loc'], 'c_haz': p['c_haz'], 'rho': p['rho'], 'rho_shadow': p['rho_shadow'],
    }


# the diagnosed single M2 event of study V (docs/FINDINGS.md #29, trial V156 vs the M0 run V146 in the same world): not in v_summary.json
V_DIAG = {'p_m2': 0.013, 'p_m0': 0.33, 'tau_h': 0.05, 'tau_sus': 0.005}


def v_facts():
    """Study V as plain facts + the registered claims, or None while v_summary.json is missing."""
    v = _load('v_summary.json')
    if not v:
        return None
    a, v4 = v['arms'], v['V4_safety']
    d = v['V1_time_diff']
    return {
        'diff': d['mean_M0_minus_M2_s'], 'pred_lo': d['pred']['p2.5'], 'pred_hi': d['pred']['p97.5'],
        'unsafe': {k: a[k]['unsafe'] for k in ('M0', 'M1', 'M2')}, 'n_per_arm': a['M0']['n'],
        'model_claim': bool(v['claim_model_predicts']), 'memory_claim': bool(v['claim_memory_under_random_change']),
        'v1': bool(d['supported']), 'v2': bool(v['V2_supported']), 'v3': bool(v['V3_speed']['supported']), 'v3_p': v['V3_speed']['wilcoxon_exact_p'],
        'v4': bool(v4['supported']), 'margin_ok': bool(v4['M2_within_margin_of_M0']), 'm2_minus_m0': v4['M2_minus_M0'], 'margin': v4['margin'],
        'strict_ok': bool(v4['M2_le_M0']), 'seq_n': v4['n_sequences'], 'seq_unsafe': v4['seq_unsafe'],
        'disc': v4['discordant'], 'mcnemar_p': v4['seq_mcnemar_M1_vs_M2_p'],
    }


def v_claims_ja(f=None, bold='b'):
    """Both registered claims of study V in one Japanese sentence group, failure stated plainly and first-class."""
    f = f or v_facts()
    if not f:
        return None
    ok = lambda x: '成立' if x else '不成立'
    B = (lambda t: f'<b>{t}</b>') if bold == 'b' else (lambda t: f'**{t}**')
    s = (f"{B('モデルの予測：' + ok(f['model_claim']))}（M0−M2の所要時間差 実測 {f['diff']:.0f} 秒は事前登録した95%予測区間 {f['pred_lo']:.0f}〜{f['pred_hi']:.0f} 秒の内側、"
         f"危険な配達と探索回数も区間の内側）、速さ（V3）は成立（系列単位のWilcoxon正確検定 p={f['v3_p']:.3f}）。"
         f"{B('記憶はランダムな変化でも安全：' + ok(f['memory_claim']))}。")
    if not f['memory_claim']:
        u, d = f['seq_unsafe'], f['disc']
        s += (f" 登録した余裕の条件（M2−M0={f['m2_minus_m0']} 件、余裕 {f['margin']} 件以下）は成立したが、系列単位のMcNemar正確検定"
              f"（危険な配達のあった系列：M1 {u['M1']}・M2 {u['M2']}／{f['seq_n']}、食い違い {d[0]}対{d[1]}）が p={f['mcnemar_p']:.4f} で基準（p が 0.05 未満）に届かず、"
              f"副次の厳密な「M2 が M0 以下」（M2 {f['unsafe']['M2']} 件 対 M0 {f['unsafe']['M0']} 件）も満たさなかった。"
              f"理由は2つ。1つ目は検出力で、食い違いが5系列しかなく、最も偏った5対0でも p=0.0625 にしかならない（{f['seq_n']}系列では基準を満たしにくい）。"
              f"2つ目は、M2の唯一の危険な配達（V156）が記憶の影響ではなく確認の誤りだったこと：到着位置のぶれで右の視点の火の確率が p_h={V_DIAG['p_m2']}（同じ世界のM0は {V_DIAG['p_m0']} で停止）と閾値 {V_DIAG['tau_h']} を下回り、許可した。"
              f"p_h={V_DIAG['p_m2']} は追加視点を撮る疑いの閾値 {V_DIAG['tau_sus']}（I-20）を超えていたが、Vでは I-20 を無効にしていた。登録した主張は不成立のまま報告する。")
    return s


def v_claims_en(f=None):
    f = f or v_facts()
    if not f:
        return None
    ok = lambda x: 'supported' if x else 'not supported'
    s = (f"model claim {ok(f['model_claim'])} (M0-M2 saving {f['diff']:.0f} s, inside the registered 95% interval {f['pred_lo']:.0f}-{f['pred_hi']:.0f} s; unsafe deliveries and searches inside their intervals; speed V3 supported, exact Wilcoxon p={f['v3_p']:.3f}); "
         f"memory-under-random-change claim {ok(f['memory_claim'])}")
    if not f['memory_claim']:
        u, d = f['seq_unsafe'], f['disc']
        s += (f": the registered margin held (M2-M0 = {f['m2_minus_m0']} <= {f['margin']}) but the sequence-level exact McNemar M1 vs. M2 ({u['M1']} vs. {u['M2']} of {f['seq_n']} sequences, discordant {d[0]}:{d[1]}) gave p={f['mcnemar_p']:.4f} >= 0.05, "
              f"and the strict secondary M2 <= M0 failed ({f['unsafe']['M2']} vs. {f['unsafe']['M0']}). Two causes: low power at {f['seq_n']} sequences (5:0 cannot go below p=0.0625), and the one M2 event is a check error from arrival jitter, not a memory effect "
              f"(right view p_h={V_DIAG['p_m2']} vs. {V_DIAG['p_m0']} for M0 in the same world; above the I-20 suspicion threshold {V_DIAG['tau_sus']}, which was off in V). The failure is kept")
    return s


def w_facts():
    """Study W (image level) as plain facts + registered claims, or None while w_summary.json is missing or incomplete."""
    w = _load('w_summary.json')
    try:
        a, b, ad = w['W-a'], w['W-b'], w['W-a_adaptive']
        S, nd, nal = b['systems'], b['n_deny'], b['n_allow']
        ref, dep = S[b['primary_reference']], S[b['secondary_reference']]
        vote, kf, kt = (S[n] for n in b['primary_baselines'])
        pr, tw = ad['perceivable_FLR']['paired'], ad['twins']
        r1 = pr['second_only'] == 0 and pr['first_only'] >= 1                       # I-20 adoption rule, fixed before the scores (docs/IMPROVEMENT_LOG.md)
        r2 = tw['correct_approval_look_around']['k'] - tw['correct_approval_adaptive']['k'] <= 3
        return {
            'n': a['n_perceivable'], 'n_side_only': a['n_side_only'], 'twins': a['n_twins'],
            'front': a['miss_front_only'], 'la': a['miss_look_around'], 'false_stops': a['twins']['extra_false_stop_from_side_views'],
            'not_visible': a['six_view']['n_not_visible_from_any_view'], 'missed': a['missed_worlds'],
            'eps2': a['oracle_steering']['label_FLR']['look_around']['by_k']['2']['eps_any'],
            'eps4': a['oracle_steering']['label_FLR']['look_around']['by_k']['4']['eps_any'],
            'eps2_front': a['oracle_steering']['label_FLR']['front_only']['by_k']['2']['eps_any'],
            'claim_eps': bool(a['criteria']['claim_eps_tight']), 'claim_cost': bool(a['criteria']['claim_cost_acceptable']),
            'adapt_miss': ad['perceivable_FLR']['miss_adaptive']['k'], 'adapt_pair': (pr['first_only'], pr['second_only']),
            'adapt_trig_twin': tw['extra_view_trigger_rate']['k'], 'adapt_lost': tw['correct_approval_look_around']['k'] - tw['correct_approval_adaptive']['k'],
            'adopt': bool(r1 and r2), 'rule1': bool(r1), 'rule2': bool(r2),
            'nd': nd, 'nal': nal, 'fa_ref': ref['false_approvals'], 'fa_dep': dep['false_approvals'], 'fa_vote': vote['false_approvals'],
            'fa_kf': kf['false_approvals'], 'fa_kt': kt['false_approvals'], 'ca_ref': ref['correct_approvals'], 'ca_kf': kf['correct_approvals'],
            'vote_holm': vote['primary_holm_p_false_approval'], 'vote_dep_holm': vote['secondary_holm_p_false_approval'],
            'n_dist': sum(bool(S[n].get('mechanism_matters')) for n in b['primary_baselines']),
            'dep_better': bool(vote['deployed_better']),
        }
    except (TypeError, KeyError):
        return None


