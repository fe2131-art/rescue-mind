#!/usr/bin/env python3
"""Video v12 card (study QI): one simulator frame next to its photographically realised frame, with the frozen gate's score on each (docs/figures/qi_strip.png).

  python3 scripts/make_qi_strip.py [--world xd198 --view R]
The pair is a world that the gate caught on the simulator frame and missed after realisation (one of the newly missed worlds of qi_summary.json), chosen by the rule "largest score drop".
Both images are simulator output or generated by an image model; neither is a real photograph, and the strip says so.
"""
import argparse
import json
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from xd_analysis import hazard_score  # noqa: E402

RES = ROOT / 'experiments/results'
FONT_B = '/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc'
FONT_R = '/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc'


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--world')
    ap.add_argument('--view')
    a = ap.parse_args(argv)
    s = json.loads((RES / 'qi_summary.json').read_text())
    newly = [w for w in s['R']['miss']['worlds'] if w not in s['xd_baseline']['miss']['worlds']]
    R = {(r['world_id'], r['view']): r for r in json.loads((RES / 'devset_qi_R_h36_tiles.json').read_text())['records']}
    X = {(r['world_id'], r['view']): r for r in json.loads((RES / 'devset_xd_h36_tiles.json').read_text())['records']}
    if a.world:
        key = (a.world, a.view)
    else:
        key = max(((w, v) for w in newly for v in 'FLR' if (w, v) in R and (w, v) in X and R[(w, v)].get('fire_pixels', 0) >= 614 and X[(w, v)].get('fire_pixels', 0) >= 614),
                  key=lambda k: hazard_score(X[k]) - hazard_score(R[k]))
    sx, sr = hazard_score(X[key]), hazard_score(R[key])
    img_x = Image.open(ROOT / 'experiments/vlm_testset_xd' / X[key]['image']).convert('RGB').resize((780, 585))
    img_r = Image.open(ROOT / 'outputs/qi/devset_R' / R[key]['image']).convert('RGB').resize((780, 585))
    W, H = 1600, 800
    canvas = Image.new('RGB', (W, H), (24, 28, 36))
    d = ImageDraw.Draw(canvas)
    fb, fr = ImageFont.truetype(FONT_B, 44), ImageFont.truetype(FONT_R, 34)
    canvas.paste(img_x, (10, 70))
    canvas.paste(img_r, (810, 70))
    d.text((10, 8), 'シミュレータの画像', font=fb, fill=(255, 255, 255))
    d.text((810, 8), '画像生成AIで写実化した画像', font=fb, fill=(255, 255, 255))
    d.text((10, 665), f'AIが判断した火の確率 {sx:.2f} → 火を検知', font=fb, fill=(120, 220, 140))
    d.text((810, 665), f'AIが判断した火の確率 {sr:.2f} → 見逃し', font=fb, fill=(255, 120, 110))
    d.text((10, 722), '写真に近い背景では煙だけが目立ち、AIは火と判断しなかった（どちらも生成画像）。', font=fr, fill=(210, 210, 210))
    out = ROOT / 'docs/figures/qi_strip.png'
    canvas.save(out)
    print(key, round(sx, 3), round(sr, 3), out)


if __name__ == '__main__':
    main()
